export function getLocalizedLesson(
  lesson: Lesson,
  language: LessonLanguage,
): Lesson {
  if (language === 'en') return lesson

  const translation = LESSON_TRANSLATIONS[lesson.id]?.[language]

  if (!translation) return lesson

  return {
    ...lesson,
    ...translation,
    // Keep the original lesson ID and programming example code.
    id: lesson.id,
    example: {
      ...lesson.example,
      title: translation.example?.title ?? lesson.example.title,
      code: lesson.example.code,
      lang: lesson.example.lang,
    },
  }
}
